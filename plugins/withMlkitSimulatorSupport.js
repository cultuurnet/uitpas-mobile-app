const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

function loadConfigPlugins() {
  try {
    return require('@expo/config-plugins');
  } catch (error) {
    if (error.code !== 'MODULE_NOT_FOUND') {
      throw error;
    }

    // pnpm does not hoist Expo's dependencies, so resolve the plugin package
    // through Expo's own node_modules tree.
    const expoPackage = require.resolve('expo/package.json');
    return require(require.resolve('@expo/config-plugins', { paths: [path.dirname(expoPackage)] }));
  }
}

const { withDangerousMod, withXcodeProject } = loadConfigPlugins();

const PODFILE_MARKER = '# Generated by plugins/withMlkitSimulatorSupport.js. Do not edit manually.';
const PODFILE_POST_INTEGRATE_MARKER =
  '# Generated by plugins/withMlkitSimulatorSupport.js for build phase ordering. Do not edit manually.';
const BUILD_PHASE_NAME = 'Relabel ML Kit arm64 slices';
const BUILD_PHASE_SCRIPT = '"$SRCROOT/scripts/relabel-mlkit-arm64.sh"\n';

const PODFILE_SNIPPET = `${PODFILE_MARKER}
  # ML Kit sets EXCLUDED_ARCHS[sdk=iphonesimulator*] = arm64. Xcode 26+ simulators
  # are arm64-only, so remove the exclusion and let relabel-mlkit-arm64.sh change
  # the vendored arm64 slices to the arm64 simulator platform.
  if installer.pods_project
    installer.pods_project.targets.each do |target|
      target.build_configurations.each do |target_config|
        target_config.build_settings.delete('EXCLUDED_ARCHS[sdk=iphonesimulator*]')
      end
    end

    installer.pods_project.save

    pattern = File.join(installer.sandbox.root, 'Target Support Files', '**', '*.xcconfig')
    Dir.glob(pattern).each do |xcconfig_path|
      lines = File.readlines(xcconfig_path)
      filtered_lines = lines.reject { |line| line.start_with?('EXCLUDED_ARCHS[sdk=iphonesimulator*]') }
      File.write(xcconfig_path, filtered_lines.join) if filtered_lines.length != lines.length
    end
  end`;

const POST_INTEGRATE_CODE = `  # CocoaPods prepends [CP] Check Pods Manifest.lock during integration. Move the
  # ML Kit relabel phase back to the front so it runs before the linker.
  projects = installer.aggregate_targets.map(&:user_project).compact.uniq
  projects.each do |project|
    project.targets.each do |target|
      phase = target.build_phases.find do |candidate|
        candidate.respond_to?(:name) && candidate.name == '${BUILD_PHASE_NAME}'
      end
      next if phase.nil?

      target.build_phases.delete(phase)
      target.build_phases.unshift(phase)
    end
    project.save
  end

  # CocoaPods writes the aggregate target xcconfigs after post_install, so strip
  # the simulator exclusion again once integration has finished.
  pattern = File.join(installer.sandbox.root, 'Target Support Files', '**', '*.xcconfig')
  Dir.glob(pattern).each do |xcconfig_path|
    lines = File.readlines(xcconfig_path)
    filtered_lines = lines.reject { |line| line.start_with?('EXCLUDED_ARCHS[sdk=iphonesimulator*]') }
    File.write(xcconfig_path, filtered_lines.join) if filtered_lines.length != lines.length
  end`;

const PODFILE_POST_INTEGRATE_BLOCK = `${PODFILE_POST_INTEGRATE_MARKER}
post_integrate do |installer|
${POST_INTEGRATE_CODE}
end`;
const PODFILE_POST_INTEGRATE_INNER = `${PODFILE_POST_INTEGRATE_MARKER}
${POST_INTEGRATE_CODE}`;

function unquote(value) {
  if (typeof value !== 'string') {
    return value;
  }

  const match = value.match(/^"(.*)"$/);
  return match ? match[1] : value;
}

function withMlkitSimulatorPodfile(config) {
  return withDangerousMod(config, [
    'ios',
    async config => {
      const projectRoot = config.modRequest.projectRoot;
      const iosRoot = path.join(projectRoot, 'ios');
      if (!fs.existsSync(iosRoot)) {
        return config;
      }

      const sourceScript = path.join(__dirname, 'scripts', 'relabel-mlkit-arm64.sh');
      const destinationScript = path.join(iosRoot, 'scripts', 'relabel-mlkit-arm64.sh');
      await fs.promises.mkdir(path.dirname(destinationScript), { recursive: true });
      await fs.promises.copyFile(sourceScript, destinationScript);
      await fs.promises.chmod(destinationScript, 0o755);

      const podfilePath = path.join(iosRoot, 'Podfile');
      if (!fs.existsSync(podfilePath)) {
        return config;
      }

      const podfile = await fs.promises.readFile(podfilePath, 'utf8');
      let updatedPodfile = podfile;

      if (!updatedPodfile.includes(PODFILE_MARKER)) {
        const postInstallMatch = updatedPodfile.match(/^[ \t]*post_install do \|installer\|[ \t]*\r?\n/m);

        if (postInstallMatch) {
          const insertAt = postInstallMatch.index + postInstallMatch[0].length;
          updatedPodfile = `${updatedPodfile.slice(0, insertAt)}${PODFILE_SNIPPET}\n\n${updatedPodfile.slice(insertAt)}`;
        } else {
          const separator = updatedPodfile.endsWith('\n') ? '\n' : '\n\n';
          updatedPodfile = `${updatedPodfile}${separator}post_install do |installer|\n${PODFILE_SNIPPET}\nend\n`;
        }
      }

      if (!updatedPodfile.includes(PODFILE_POST_INTEGRATE_MARKER)) {
        const postIntegrateMatch = updatedPodfile.match(/^[ \t]*post_integrate do \|installer\|[ \t]*\r?\n/m);

        if (postIntegrateMatch) {
          const insertAt = postIntegrateMatch.index + postIntegrateMatch[0].length;
          updatedPodfile = `${updatedPodfile.slice(0, insertAt)}${PODFILE_POST_INTEGRATE_INNER}\n\n${updatedPodfile.slice(
            insertAt,
          )}`;
        } else {
          const separator = updatedPodfile.endsWith('\n') ? '\n' : '\n\n';
          updatedPodfile = `${updatedPodfile}${separator}${PODFILE_POST_INTEGRATE_BLOCK}\n`;
        }
      }

      if (updatedPodfile !== podfile) {
        await fs.promises.writeFile(podfilePath, updatedPodfile, 'utf8');
      }

      return config;
    },
  ]);
}

function withMlkitSimulatorBuildPhase(config) {
  return withXcodeProject(config, config => {
    const project = config.modResults;
    if (!project || !project.hash || !project.hash.project || !project.hash.project.objects) {
      return config;
    }

    const objects = project.hash.project.objects;
    const shellScriptPhases = objects.PBXShellScriptBuildPhase || (objects.PBXShellScriptBuildPhase = {});
    const alreadyPresent = Object.values(shellScriptPhases).some(
      phase => phase && phase.isa === 'PBXShellScriptBuildPhase' && unquote(phase.name) === BUILD_PHASE_NAME,
    );
    if (alreadyPresent) {
      return config;
    }

    const nativeTargets = objects.PBXNativeTarget || {};
    const applicationTarget = Object.values(nativeTargets).find(
      target =>
        target && target.isa === 'PBXNativeTarget' && unquote(target.productType) === 'com.apple.product-type.application',
    );
    if (!applicationTarget) {
      return config;
    }

    if (!Array.isArray(applicationTarget.buildPhases)) {
      applicationTarget.buildPhases = [];
    }

    const uuid =
      typeof project.generateUuid === 'function' ? project.generateUuid() : crypto.randomBytes(12).toString('hex').toUpperCase();
    const shellScript = `"${BUILD_PHASE_SCRIPT.replace(/"/g, '\\"')}"`;

    shellScriptPhases[uuid] = {
      alwaysOutOfDate: 1,
      buildActionMask: 2147483647,
      files: [],
      inputFileListPaths: [],
      inputPaths: [],
      isa: 'PBXShellScriptBuildPhase',
      name: `"${BUILD_PHASE_NAME}"`,
      outputFileListPaths: [],
      outputPaths: [],
      runOnlyForDeploymentPostprocessing: 0,
      shellPath: '/bin/sh',
      shellScript,
      showEnvVarsInLog: 0,
    };
    shellScriptPhases[`${uuid}_comment`] = BUILD_PHASE_NAME;
    applicationTarget.buildPhases.unshift({ comment: BUILD_PHASE_NAME, value: uuid });

    return config;
  });
}

module.exports = function withMlkitSimulatorSupport(config) {
  config = withMlkitSimulatorPodfile(config);
  config = withMlkitSimulatorBuildPhase(config);
  return config;
};
